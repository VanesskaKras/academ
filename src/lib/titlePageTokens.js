// Спільні допоміжні функції для токенів титульної сторінки (використовуються і при
// попередньому заповненні titlePageLines у academic-assistant.jsx, і при фінальному
// рендері docx у exportDocx.js). Винесено окремо, щоб обидва місця підставляли
// однакові значення й не розходились між "попереднім переглядом" і фінальним файлом.

// Освітній ступінь (для токена [ОКР]) з info.type ("Магістерська", "Бакалаврська робота" тощо).
// Клієнт майже ніколи не вказує ступінь окремим полем — тип роботи вже й так його визначає,
// а без цієї похідної [ОКР] лишається порожнім і в титулку проривається буквальний ступінь
// чужого зразка з методички (напр. "бакалавр" у роботі, яка насправді магістерська).
export function deriveDegreeLevelFromType(type) {
  const t = (type || "").toLowerCase();
  if (/маг[іi]стр/.test(t)) return "магістр";
  if (/бакалавр/.test(t)) return "бакалавр";
  if (/спеціал[іi]ст/.test(t)) return "спеціаліст";
  return null;
}

// Літери-маркери, за якими сама методичка (не клієнтське замовлення) описує чужий,
// уже заповнений зразок ступеня в Додатку — використовуються для детермінованого
// (не-ШІ) фільтра-страховки в exportDocx.js: якщо після токенізації в тексті титулки
// лишився буквальний "ступеня «бакалавр»"/"«магістр»", що не збігається з фактичним
// ступенем цього замовлення, це майже напевно недогляд кроку читання методички.
const DEGREE_WORD_RE = /(бакалавра?|магістра?|спеціаліста?)/gi;

// Знаходить у тексті рядка титулки буквальний ступінь ("...ступеня «бакалавр»" чи
// "...ОКР бакалавр" без лапок) і замінює його на правильний, якщо він відомий і не
// збігається. Повертає текст без змін, якщо підозрілого патерну немає або ступінь
// уже правильний.
export function fixMismatchedDegreeWord(text, correctDegreeLevel) {
  if (!text || !correctDegreeLevel) return text;
  if (!/ступен|окр\b/i.test(text)) return text;
  return text.replace(DEGREE_WORD_RE, (match) => {
    const isCorrect = match.toLowerCase().startsWith(correctDegreeLevel.toLowerCase());
    return isCorrect ? match : correctDegreeLevel;
  });
}
